#!/usr/bin/env python3
"""Generate olake/olake-protocol/references/compatibility-matrix.md from the skills in the tree.

Nothing is read from the olake repo: the matrix lists what these skills cover, so it grows as skills
are added. Per skill it reads:
  - driver skills (olake/drivers/olake-driver-<name>/): the "Sync modes:" line of SKILL.md
  - destination skills (olake/destination/olake-destination-<name>/): references/catalogs/*.md,
    and references/storage/*.md or the "## " headings of references/storage.md
  - deploy skills (olake/deploy/*/)
  - run modes: the "Run mode" row of olake-protocol/SKILL.md
Draft skills (description starts with TODO) are left out.

--ref reads a git ref instead of the working tree, to see the matrix another branch would get.

  python tools/gen_matrix.py                                  # write the file
  python tools/gen_matrix.py --check                          # exit 1 if the file would change
  python tools/gen_matrix.py --ref origin/feat/olake-sources  # print the matrix of another branch
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = "olake/olake-protocol/references/compatibility-matrix.md"
MARKER = "<!-- generated by tools/gen_matrix.py from the skills in this repo: do not edit -->"
SYNC_MODES_RE = re.compile(r"Sync modes?: (.*?)(?:\.\s|\.$)", re.S)


class Tree:
    """Lists and reads repo files from the working tree or from a git ref."""

    def __init__(self, ref):
        self.ref = ref
        if ref:
            out = subprocess.run(
                ["git", "-C", str(ROOT), "ls-tree", "-r", "--name-only", ref, "--", "olake"],
                capture_output=True, text=True, check=True,
            ).stdout
            self.files = set(out.split())
        else:
            self.files = {p.relative_to(ROOT).as_posix() for p in (ROOT / "olake").rglob("*") if p.is_file()}

    def read(self, path):
        if self.ref:
            return subprocess.run(
                ["git", "-C", str(ROOT), "show", f"{self.ref}:{path}"],
                capture_output=True, text=True, check=True,
            ).stdout
        return (ROOT / path).read_text()

    def skills(self, group):
        """Return (skill dir, frontmatter, body) for every non-draft skill under olake/<group>/."""
        found = []
        for path in sorted(self.files):
            parts = path.split("/")
            if len(parts) != 4 or parts[1] != group or parts[3] != "SKILL.md":
                continue
            _, front, body = self.read(path).split("---", 2)
            meta = yaml.safe_load(front)
            if str(meta.get("description", "")).startswith("TODO"):
                continue
            found.append(("/".join(parts[:3]), meta, body))
        return found

    def listed(self, folder):
        """Return the stems of the .md files directly in folder."""
        return sorted(
            Path(p).stem for p in self.files
            if p.startswith(folder + "/") and p.endswith(".md") and "/" not in p[len(folder) + 1:]
        )


def title(body, suffix):
    """Return the first "# " heading with the trailing suffix word removed."""
    for line in body.splitlines():
        if line.startswith("# "):
            return re.sub(rf"\s+{suffix}$", "", line[2:].strip())
    return ""


def link(skill_dir, name):
    return f"[`{name}`](../../{skill_dir.removeprefix('olake/')}/SKILL.md)"


def sync_modes(skill_dir, body):
    match = SYNC_MODES_RE.search(body)
    if not match:
        sys.exit(f"{skill_dir}/SKILL.md: no 'Sync modes:' line")
    text = " ".join(match.group(1).split())
    modes = ", ".join(re.findall(r"`[^`]+`", text))
    return modes + (" only" if text.endswith(" only") or " only " in text else "")


def refs(tree, skill_dir, kind):
    """Catalog or storage list for a destination skill, as links or plain names."""
    folder = f"{skill_dir}/references/{kind}"
    stems = tree.listed(folder)
    if stems:
        rel = folder.removeprefix("olake/")
        return ", ".join(f"[{s}](../../{rel}/{s}.md)" for s in stems)
    single = f"{folder}.md"
    if single in tree.files:
        heads = [line[3:].strip() for line in tree.read(single).splitlines() if line.startswith("## ")]
        return ", ".join(heads)
    return "—"


def render(tree):
    sources = [
        f"| {title(body, 'source')} | {sync_modes(d, body)} | {link(d, meta['name'])} |"
        for d, meta, body in tree.skills("drivers")
        if not meta["name"].endswith("-abstract")
    ]
    destinations = [
        f"| {title(body, 'destination')} | {refs(tree, d, 'catalogs')} | {refs(tree, d, 'storage')} | {link(d, meta['name'])} |"
        for d, meta, body in tree.skills("destination")
        if not meta["name"].endswith("-abstract")
    ]
    deploys = [link(d, meta["name"]) for d, meta, _ in tree.skills("deploy")]
    run_modes = next(
        re.findall(r"`[^`]+`", line.split("|")[2])
        for line in tree.read("olake/olake-protocol/SKILL.md").splitlines()
        if line.startswith("| Run mode |")
    )

    return "\n".join([
        MARKER,
        "",
        "# Compatibility matrix",
        "",
        "What these skills cover. Every source image writes every destination, so any source below works",
        "with any destination below. Anything not listed has no skill yet: run the base steps in `SKILL.md`",
        "and use the connector and writer pages on https://olake.io/docs.",
        "",
        "## Sources",
        "",
        "| Source | Sync modes | Skill |",
        "| --- | --- | --- |",
        *sources,
        "",
        "## Destinations",
        "",
        "| Destination | Catalogs | Storage | Skill |",
        "| --- | --- | --- | --- |",
        *destinations,
        "",
        "## Run modes and deployment",
        "",
        f"- Run modes: {', '.join(run_modes)}",
        f"- Deploy skills: {', '.join(deploys) if deploys else 'none yet'}",
        "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is out of date")
    parser.add_argument("--ref", help="read this git ref and print the matrix instead of writing it")
    args = parser.parse_args()

    text = render(Tree(args.ref))
    if args.ref:
        print(text, end="")
        return
    path = ROOT / OUT
    if args.check:
        if path.read_text() != text:
            sys.exit(f"{OUT} is out of date: run python tools/gen_matrix.py")
        print(f"OK: {OUT} is up to date")
        return
    path.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
