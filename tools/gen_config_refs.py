#!/usr/bin/env python3
"""Generate the per-driver and per-destination reference files from the olake release in OLAKE_VERSION.

For every driver skill (olake/drivers/olake-driver-<name>/) this writes:
  - references/config.md        from drivers/<name>/resources/spec.json
  - references/type-mapping.md  from drivers/<name>/internal/datatype_conversion.go (when it exists)

For every destination skill (olake/destination/olake-destination-<name>/) this writes:
  - references/config.md        from destination/<name>/resources/spec.json

Both files are fully generated: edit the generator or the olake source, never the output.

Sources are read at the OLAKE_VERSION tag, from a local olake checkout (--olake-repo, uses
`git show <tag>:<path>`) or from GitHub when no checkout is given.

  python tools/gen_config_refs.py                          # write files, fetch from GitHub
  python tools/gen_config_refs.py --olake-repo ../olake    # write files from a local checkout
  python tools/gen_config_refs.py --check                  # exit 1 if any file would change
"""

import argparse
import json
import re
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DRIVERS_DIR = ROOT / "olake" / "drivers"
DESTINATIONS_DIR = ROOT / "olake" / "destination"
GITHUB_RAW = "https://raw.githubusercontent.com/datazip-inc/olake/{tag}/{path}"
GITHUB_BLOB = "https://github.com/datazip-inc/olake/blob/{tag}/{path}"
MARKER = "<!-- generated by tools/gen_config_refs.py from olake {tag}: do not edit -->"
SECRET_HINTS = ("password", "secret", "private_key", "passphrase", "token", "jaas", "client_key")
TYPE_ENTRY_RE = re.compile(r'^\s*"([^"]+)"\s*:\s*(?:types\.(\w+)|(\w+))\s*,')
MAP_START_RE = re.compile(r"^\s*(?:var\s+)?(\w+)\s*=\s*map\[string\]types\.DataType\s*{")
# A map built inside a function: `func name() map[string]types.DataType { ... return map[...]{`
FUNC_RE = re.compile(r"^func\s+(?:\([^)]*\)\s*)?(\w+)\s*\(")
RETURN_MAP_RE = re.compile(r"^\s*return\s+map\[string\]types\.DataType\s*{")
# A local holding a type, e.g. `binaryTypeMapping := types.Binary`; the first assignment wins.
LOCAL_TYPE_RE = re.compile(r"^\s*(\w+)\s*:=\s*types\.(\w+)\s*$")


class Source:
    """Reads files of the olake repo at one tag."""

    def __init__(self, tag, repo):
        self.tag = tag
        self.repo = repo

    def read(self, path):
        """Return the file text, or None when it does not exist at this tag."""
        if self.repo:
            result = subprocess.run(
                ["git", "-C", str(self.repo), "show", f"{self.tag}:{path}"],
                capture_output=True,
                text=True,
            )
            return result.stdout if result.returncode == 0 else None
        url = GITHUB_RAW.format(tag=self.tag, path=path)
        try:
            with urllib.request.urlopen(url, timeout=30) as resp:
                return resp.read().decode("utf-8")
        except urllib.error.HTTPError as exc:
            if exc.code == 404:
                return None
            raise


# --- spec.json -> field rows -------------------------------------------------------------------


def discriminator(variant):
    """Return (key, value) of the property a oneOf variant pins with `const`, else (None, None)."""
    for key, prop in (variant.get("properties") or {}).items():
        if isinstance(prop, dict) and "const" in prop:
            return key, prop["const"]
    return None, None


def fmt_value(value):
    return json.dumps(value) if not isinstance(value, str) else value


def type_of(prop):
    if "oneOf" in prop and all("const" in v for v in prop["oneOf"]):
        return prop.get("type", "string")
    if "oneOf" in prop:
        return "object"
    kind = prop.get("type", "")
    if kind == "array":
        item = (prop.get("items") or {}).get("type", "")
        return f"array of {item}" if item else "array"
    return kind


def allowed_of(prop):
    if "enum" in prop:
        return [fmt_value(v) for v in prop["enum"]]
    if "oneOf" in prop and all("const" in v for v in prop["oneOf"]):
        return [fmt_value(v["const"]) for v in prop["oneOf"]]
    if "const" in prop:
        return [fmt_value(prop["const"])]
    return []


class Rows:
    """Ordered field rows, merged by path so a field reachable in several branches appears once."""

    def __init__(self):
        self.rows = {}

    def add(self, path, prop, required, condition):
        row = self.rows.get(path)
        if row is None:
            row = {
                "path": path,
                "type": type_of(prop),
                "default": prop.get("default"),
                "allowed": allowed_of(prop),
                "description": " ".join((prop.get("description") or prop.get("title") or "").split()),
                "required": set(),
                "conditions": set(),
                "always_required": False,
                "always_present": False,
                "titles": [],
            }
            self.rows[path] = row
        else:
            for value in allowed_of(prop):
                if value not in row["allowed"]:
                    row["allowed"].append(value)
            if not row["description"]:
                row["description"] = " ".join((prop.get("description") or "").split())
        if condition is None:
            row["always_present"] = True
            row["always_required"] = row["always_required"] or required
        else:
            row["conditions"].add(condition)
            if required:
                row["required"].add(condition)
        return row

    def mark_required(self, path, condition):
        row = self.rows.get(path)
        if row is None:
            return
        if condition is None:
            row["always_required"] = True
        else:
            row["required"].add(condition)


def extend(condition, path, value):
    """A branch condition is a tuple of (field path, value) pairs, all of which must hold."""
    return (condition or ()) + ((path, fmt_value(value)),)


def render_conditions(conds):
    """Render a set of conditions; merges `a = x or a = y` into `a` in (`x`, `y`) where it can."""
    conds = sorted(conds)
    keys = [k for k, _ in conds[0]]
    if all([k for k, _ in c] == keys for c in conds):
        values = [sorted({dict(c)[k] for c in conds}) for k in keys]
        product = 1
        for v in values:
            product *= len(v)
        if product == len(set(conds)):
            parts = []
            for key, vals in zip(keys, values):
                if len(vals) == 1:
                    parts.append(f"`{key}` = `{vals[0]}`")
                else:
                    parts.append(f"`{key}` in ({', '.join(f'`{v}`' for v in vals)})")
            return " and ".join(parts)
    return " or ".join(" and ".join(f"`{k}` = `{v}`" for k, v in c) for c in conds)


def walk(schema, rows, prefix="", condition=None):
    """Add every property of an object schema, then its conditional branches."""
    required = set(schema.get("required") or [])
    props = schema.get("properties") or {}
    for name, prop in props.items():
        if not isinstance(prop, dict):
            continue
        path = prefix + name
        if "const" in prop and condition is not None:
            continue  # the discriminator of the branch being walked; already listed
        rows.add(path, prop, name in required, condition)
        if "oneOf" in prop and not all("const" in v for v in prop["oneOf"]):
            for variant in prop["oneOf"]:
                key, value = discriminator(variant)
                if key is None:
                    continue
                disc = rows.add(f"{path}.{key}", variant["properties"][key], key in (variant.get("required") or []), condition)
                disc["type"] = disc["type"] or type(value).__name__.replace("str", "string").replace("bool", "boolean")
                if variant.get("title"):
                    disc["titles"].append(f"`{fmt_value(value)}` = {variant['title']}")
                walk(variant, rows, f"{path}.", extend(condition, f"{path}.{key}", value))
        elif prop.get("type") == "object" or "properties" in prop:
            walk(prop, rows, f"{path}.", condition)
    # Fields listed in `required` but defined higher up (a branch can require a sibling field).
    for name in required:
        if name not in props:
            rows.mark_required(prefix + name, condition)
    walk_dependencies(schema, rows, prefix, condition)
    for clause in schema.get("allOf") or []:
        walk_if_then(clause, rows, prefix, condition)
    if "if" in schema:
        walk_if_then(schema, rows, prefix, condition)


def walk_dependencies(schema, rows, prefix, condition):
    for key, dep in (schema.get("dependencies") or {}).items():
        if not isinstance(dep, dict):
            continue
        for branch in dep.get("oneOf") or []:
            _, value = discriminator(branch)
            if value is None:
                continue
            walk(branch, rows, prefix, extend(condition, prefix + key, value))


def walk_if_then(clause, rows, prefix, condition):
    test = (clause.get("if") or {}).get("properties") or {}
    then = clause.get("then")
    if not then:
        return
    pins = [(k, v["const"]) for k, v in test.items() if isinstance(v, dict) and "const" in v]
    if not pins:
        return
    for key, value in pins:
        condition = extend(condition, prefix + key, value)
    walk(then, rows, prefix, condition)


def required_text(row):
    if row["always_required"]:
        return "yes"
    # Required in every branch it exists in: the "only when" note already says which.
    if row["required"] and (row["required"] == row["conditions"] and not row["always_present"]):
        return "yes"
    if row["required"]:
        return f"when {render_conditions(row['required'])}"
    return "no"


def description_text(row):
    text = row["description"]
    if row["titles"]:
        text = f"{text} {'; '.join(row['titles'])}".strip()
    if text and not text.endswith((".", ")")):
        text += "."
    if not row["always_present"] and row["conditions"]:
        text = f"{text} Only when {render_conditions(row['conditions'])}.".strip()
    return text


def cell(text):
    return str(text).replace("|", "\\|")


def example_value(path, prop):
    name = path.rsplit(".", 1)[-1]
    if "default" in prop:
        return prop["default"]
    if prop.get("format") == "password" or any(h in name for h in SECRET_HINTS):
        return f"<{name.upper()}>"
    kind = prop.get("type")
    if kind == "integer":
        return 0
    if kind == "boolean":
        return False
    if kind == "array":
        return [f"<{name.upper()}>"]
    if "enum" in prop:
        return prop["enum"][0]
    return f"<{name.upper()}>"


def minimal_object(schema):
    """The always-required fields of an object schema, secrets as placeholders."""
    props = schema.get("properties") or {}
    example = {}
    for name in schema.get("required") or []:
        prop = props.get(name, {})
        if "oneOf" in prop and not all("const" in v for v in prop["oneOf"]):
            variant = prop["oneOf"][0]
            key, value = discriminator(variant)
            example[name] = {key: value} if key else {}
        elif "properties" in prop:
            example[name] = minimal_object(prop)
        else:
            example[name] = example_value(name, prop)
    return example


def minimal_example(spec):
    return json.dumps(minimal_object(spec), indent=2)


def render_config(kind, name, spec, tag):
    """kind is "source" (a driver) or "destination"."""
    rows = Rows()
    walk(spec, rows)
    if kind == "source":
        spec_path = f"drivers/{name}/resources/spec.json"
        config_file = "source.json"
        spec_cmd = f"docker run --rm olakego/source-{name}:{tag} spec"
    else:
        spec_path = f"destination/{name}/resources/spec.json"
        config_file = "destination.json"
        spec_cmd = f"docker run --rm olakego/source-<source>:{tag} spec --destination-type {name}"
    lines = [
        MARKER.format(tag=tag),
        "",
        f"# `{name}` {config_file} fields",
        "",
        f"Generated from [`{spec_path}`]({GITHUB_BLOB.format(tag=tag, path=spec_path)}) at `{tag}`. "
        f"The same schema prints with `{spec_cmd}`.",
        "",
        "Nested fields use dots: `ssl.mode` is `\"ssl\": {\"mode\": ...}`. *Required* is relative to the "
        "parent object: `ssh_config.type` is required only if `ssh_config` is set. A field marked "
        "*only when* exists only in that branch of its parent object.",
        "",
        f"## Minimal {config_file}",
        "",
        "```json",
        minimal_example(spec),
        "```",
        "",
        "## Fields",
        "",
        "| Field | Type | Required | Default | Allowed values | Description |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows.rows.values():
        default = "" if row["default"] is None else f"`{fmt_value(row['default'])}`"
        allowed = ", ".join(f"`{v}`" for v in row["allowed"])
        lines.append(
            f"| `{row['path']}` | {cell(row['type'])} | {cell(required_text(row))} | {cell(default)} | "
            f"{cell(allowed)} | {cell(description_text(row))} |"
        )
    return "\n".join(lines) + "\n"


# --- datatype_conversion.go -> type table ------------------------------------------------------


def parse_type_maps(go_source):
    """Return [(map_name, [(source_type, olake_type), ...]), ...] in file order."""
    maps = []
    current = None
    func_name = None
    local_types = {}
    for line in go_source.splitlines():
        func = FUNC_RE.match(line)
        if func:
            func_name = func.group(1)
            local_types = {}
        local = LOCAL_TYPE_RE.match(line)
        if local:
            local_types.setdefault(local.group(1), local.group(2))
        start = MAP_START_RE.match(line)
        if start or (func_name and RETURN_MAP_RE.match(line)):
            current = (start.group(1) if start else func_name, [])
            maps.append(current)
            continue
        if current is None:
            continue
        if line.strip() == "}":
            current = None
            continue
        entry = TYPE_ENTRY_RE.match(line)
        if entry:
            olake_type = entry.group(2) or local_types.get(entry.group(3))
            if olake_type:
                current[1].append((entry.group(1), olake_type))
    return [m for m in maps if m[1]]


def render_types(driver, go_source, tag):
    go_path = f"drivers/{driver}/internal/datatype_conversion.go"
    lines = [
        MARKER.format(tag=tag),
        "",
        f"# `{driver}` type mapping",
        "",
        f"Generated from [`{go_path}`]({GITHUB_BLOB.format(tag=tag, path=go_path)}) at `{tag}`. "
        "Source column type (lower-cased by the driver) to the OLake type in `available_streams.json`. "
        "A type not listed here is read as `String`. How each OLake type lands in Iceberg or Parquet: "
        "`olake-destination-abstract`.",
    ]
    for name, entries in parse_type_maps(go_source):
        grouped = {}
        for source_type, olake_type in entries:
            grouped.setdefault(olake_type, []).append(source_type)
        lines += ["", f"## `{name}`", "", "| OLake type | Source types |", "| --- | --- |"]
        for olake_type, sources in grouped.items():
            lines.append(f"| `{olake_type}` | {', '.join(f'`{cell(s)}`' for s in sources)} |")
    return "\n".join(lines) + "\n"


# --- main --------------------------------------------------------------------------------------


def driver_skills():
    for skill_dir in sorted(DRIVERS_DIR.glob("olake-driver-*")):
        name = skill_dir.name.removeprefix("olake-driver-")
        if name != "abstract":
            yield name, skill_dir


def destination_skills():
    for skill_dir in sorted(DESTINATIONS_DIR.glob("olake-destination-*")):
        name = skill_dir.name.removeprefix("olake-destination-")
        if name != "abstract":
            yield name, skill_dir


def outputs(source):
    """Yield (path, content) for every generated file."""
    for name, skill_dir in destination_skills():
        spec_text = source.read(f"destination/{name}/resources/spec.json")
        if spec_text is None:
            print(f"warning: no spec.json for destination {name} at {source.tag}", file=sys.stderr)
            continue
        yield skill_dir / "references" / "config.md", render_config("destination", name, json.loads(spec_text), source.tag)
    for driver, skill_dir in driver_skills():
        spec_text = source.read(f"drivers/{driver}/resources/spec.json")
        if spec_text is None:
            print(f"warning: no spec.json for {driver} at {source.tag}", file=sys.stderr)
            continue
        yield skill_dir / "references" / "config.md", render_config("source", driver, json.loads(spec_text), source.tag)
        go_source = source.read(f"drivers/{driver}/internal/datatype_conversion.go")
        if go_source and parse_type_maps(go_source):
            yield skill_dir / "references" / "type-mapping.md", render_types(driver, go_source, source.tag)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--olake-repo", type=Path, help="local olake checkout to read from instead of GitHub")
    parser.add_argument("--check", action="store_true", help="do not write; exit 1 if any file is out of date")
    args = parser.parse_args()

    tag = (ROOT / "OLAKE_VERSION").read_text(encoding="utf-8").strip()
    source = Source(tag, args.olake_repo)
    stale = []
    for path, content in outputs(source):
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            continue
        rel = path.relative_to(ROOT)
        if args.check:
            stale.append(str(rel))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {rel}")
    if stale:
        print("out of date (run python tools/gen_config_refs.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
